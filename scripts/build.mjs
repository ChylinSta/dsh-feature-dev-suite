/**
 * Bundle src/index.ts → lib/index.js for dsh.bundle installs.
 * Desktop and `dsh plugin add` load the prebuilt file; they do not compile TypeScript.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

await esbuild.build({
  absWorkingDir: root,
  entryPoints: ["src/index.ts"],
  bundle: true,
  platform: "node",
  format: "esm",
  outfile: "lib/index.js",
  packages: "external",
  charset: "ascii",
  legalComments: "none",
  banner: {
    js: "/** dsh-feature-dev-suite — generated by scripts/build.mjs; do not edit. */",
  },
  logLevel: "info",
});

// esbuild inserts a blank line after the banner; the published bundle does not.
const outfile = join(root, "lib/index.js");
const banner = "/** dsh-feature-dev-suite — generated by scripts/build.mjs; do not edit. */\n";
const text = readFileSync(outfile, "utf8");
if (text.startsWith(`${banner}\n`)) {
  writeFileSync(outfile, banner + text.slice(banner.length + 1));
}

await esbuild.build({
  absWorkingDir: root,
  entryPoints: ["src/core.ts"],
  bundle: true,
  platform: "node",
  format: "esm",
  outfile: "lib/core.js",
  packages: "external",
  charset: "ascii",
  legalComments: "none",
  logLevel: "info",
});

const client = readFileSync(join(root, "src/client/entry.js"), "utf8");
writeFileSync(join(root, "lib/client.js"), [
  "window.__ModuleLoader__.load({ id: \"dsh-feature-dev-suite\", factory: (require) => {",
  "var module = { exports: {} };",
  "var exports = module.exports;",
  client,
  "return module.exports;",
  "} });",
  "",
].join("\n"));
